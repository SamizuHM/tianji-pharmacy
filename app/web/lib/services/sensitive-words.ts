/**
 * 检查用户问题是否命中敏感词
 * @returns 命中的敏感词数组，未命中返回空数组
 */
export function matchSensitiveTerms(text: string): string[] {
  const normalized = text.toLowerCase();
  return SENSITIVE_TERMS.filter((term) => normalized.includes(term.toLowerCase()));
}

/**
 * 判断用户问题是否涉及敏感领域
 */
export function isSensitiveQuery(text: string): boolean {
  return matchSensitiveTerms(text).length > 0;
}
